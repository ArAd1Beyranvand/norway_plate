  /// The county of [letters] (one or two), or null when they match no series
  /// or several counties.
  static String? lookup(String letters) {
    if (letters.isEmpty) return null;
    final Set<String> names = <String>{
      for (final MapEntry<String, String> e in _counties.entries)
        if (e.key.startsWith(letters)) e.value,
    };
    return names.length == 1 ? names.single : null;
  }

